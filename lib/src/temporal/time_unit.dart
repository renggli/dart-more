/// Different units of time.
///
/// See https://en.wikipedia.org/wiki/Unit_of_time#List.
enum TimeUnit {
  /// A microsecond (one millionth of a second).
  microsecond,

  /// A millisecond (one thousandth of a second).
  millisecond,

  /// A second.
  second,

  /// A minute (60 seconds).
  minute,

  /// An hour (60 minutes).
  hour,

  /// A day (24 hours).
  day,

  /// A week (7 days).
  week,

  /// A calendar month.
  month,

  /// A quarter of a year (3 months).
  quarter,

  /// A calendar year.
  year,

  /// A decade (10 years).
  decade,

  /// A century (100 years).
  century,

  /// A millennium (1000 years).
  millennium,
}
